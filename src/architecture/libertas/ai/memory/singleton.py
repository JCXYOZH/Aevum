def remember(content: str, **kwargs) -> Memory:
    return get_memory_system().add_long_term(content=content, **kwargs)


def recall(query: str, **kwargs) -> List[Dict[str, Any]]:
    return get_memory_system().retrieve(query, **kwargs)
