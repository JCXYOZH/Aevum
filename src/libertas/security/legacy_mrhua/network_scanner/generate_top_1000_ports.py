class ScanStatus(Enum):
    PENDING = "pending"
    RUNNING = "running"
    PAUSED = "paused"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"

class ScanTechnique(Enum):
    TCP_CONNECT = "tcp_connect"
    TCP_SYN = "tcp_syn"
    TCP_ACK = "tcp_ack"
    TCP_FIN = "tcp_fin"
    TCP_NULL = "tcp_null"
    TCP_XMAS = "tcp_xmas"
    UDP = "udp"
    ICMP_PING = "icmp_ping"
    ARP = "arp"

@dataclass
class ScanTask:
    """扫描任务"""
    task_id: str
    name: str
    targets: List[str]  # IP列表或CIDR或域名
    ports: List[int]
    technique: str = "tcp_connect"
    status: str = "pending"
    created_at: float = field(default_factory=time.time)
    started_at: Optional[float] = None
    completed_at: Optional[float] = None
    total_targets: int = 0
    scanned_targets: int = 0
    total_ports: int = 0
    open_ports: int = 0
    filtered_ports: int = 0
    closed_ports: int = 0
    assets_found: int = 0
    progress: float = 0.0
    error: Optional[str] = None
    options: Dict = field(default_factory=dict)

    def to_dict(self) -> Dict:
        return asdict(self)

@dataclass
class ScanProgress:
    """扫描进度快照"""
    task_id: str
    status: str
    progress: float
    scanned_targets: int
    total_targets: int
    open_ports: int
    filtered_ports: int
    closed_ports: int
    assets_found: int
    elapsed_time: float
    estimated_remaining: float
    current_ip: str
    current_port: int

@dataclass
class PortScanResult:
    """端口扫描结果"""
    ip: str
    port: int
    state: str  # open/closed/filtered/open|filtered
    service: str = ""
    version: str = ""
    banner: str = ""
    protocol: str = "tcp"
    latency: float = 0.0
    reason: str = ""

@dataclass
class HostScanResult:
    """主机扫描结果"""
    ip: str
    hostname: str = ""
    domain: str = ""
    os: str = ""
    os_version: str = ""
    status: str = "unknown"  # up/down/unknown
    latency: float = 0.0
    ports: List[PortScanResult] = field(default_factory=list)
    fingerprints: List[Dict] = field(default_factory=list)
    cves: List[Dict] = field(default_factory=list)
    risk_score: float = 0.0
    tags: List[str] = field(default_factory=list)
    extra: Dict = field(default_factory=dict)

    def to_dict(self) -> Dict:
        d = asdict(self)
        d["ports"] = [asdict(p) for p in self.ports]
        return d
