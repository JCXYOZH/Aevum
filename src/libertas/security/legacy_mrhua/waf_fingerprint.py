def detect_waf(
    status_code: int = 0,
    headers: Optional[Dict] = None,
    cookies: Optional[Dict] = None,
    body: str = "",
) -> List[Dict]:
    """检测WAF指纹。

    Args:
        status_code: HTTP状态码
        headers: 响应头字典
        cookies: Cookie字典
        body: 响应体文本

    Returns:
        检测到的WAF列表，每个元素含 name/vendor/confidence/evidence
    """
    headers = {k.lower(): v for k, v in (headers or {}).items()}
    cookie_names = list((cookies or {}).keys())
    if not cookie_names and headers.get("set-cookie"):
        try:
            for part in str(headers["set-cookie"]).split(";"):
                if "=" in part:
                    cookie_names.append(part.split("=")[0].strip())
        except Exception:
            pass
    body_lower = body[:5000].lower() if body else ""

    results = []
    for sig in WAF_SIGNATURES:
        score = 0
        evidence = []

        for hname, pattern in sig.get("headers", {}).items():
            hval = headers.get(hname.lower(), "")
            if hval and re.search(pattern, str(hval), re.IGNORECASE):
                score += 3
                evidence.append(f"header:{hname}={hval[:60]}")

        for cpat in sig.get("cookies", []):
            for cn in cookie_names:
                if re.search(cpat, cn, re.IGNORECASE):
                    score += 2
                    evidence.append(f"cookie:{cn}")
                    break

        for marker in sig.get("body_markers", []):
            if body_lower and re.search(marker, body_lower, re.IGNORECASE):
                score += 1
                evidence.append(f"body:{marker[:40]}")

        if status_code and status_code in sig.get("status_blocked", []):
            score += 1
            evidence.append(f"status:{status_code}")

        if score >= 3:
            confidence = "high" if score >= 6 else "medium" if score >= 4 else "low"
            results.append({
                "name": sig["name"],
                "vendor": sig.get("vendor", sig["name"]),
                "confidence": confidence,
                "score": score,
                "evidence": evidence[:5],
            })

    results.sort(key=lambda x: x["score"], reverse=True)
    return results


def is_blocked_by_waf(status_code: int, headers: Optional[Dict] = None, body: str = "") -> Optional[str]:
    """快速判断响应是否被WAF拦截。

    Returns:
        WAF名称（如果被拦截），否则None
    """
    wafs = detect_waf(status_code, headers, body=body)
    if not wafs:
        return None
    blocked_statuses = {403, 406, 429, 444, 494, 495, 496, 501, 503, 567}
    if status_code in blocked_statuses:
        return wafs[0]["name"]
    body_lower = (body or "")[:3000].lower()
    block_markers = ["blocked", "forbidden", "denied", "拦截", "拒绝", "访问被阻止",
                     "request rejected", "access denied", "security violation",
                     "not acceptable", "rate limit", "too many requests"]
    if any(m in body_lower for m in block_markers):
        return wafs[0]["name"]
    return None
