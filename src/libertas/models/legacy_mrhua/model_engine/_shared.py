def is_placeholder_key(key: str) -> bool:
    """判断密钥是否明显不是有效值（空 / 过短 / sk-xxxx 这类占位符）。"""
    k = (key or "").strip()
    if len(k) < 10:
        return True
    body_value = k[3:] if k[:3].lower() in ("sk-", "sk_") else k
    if body_value and set(body_value.lower()) <= {"x"}:
        return True
    low = k.lower()
    for prefix in ("sk-xxx", "sk_xxx", "your", "xxx", "placeholder", "changeme", "todo"):
        if low.startswith(prefix):
            return True
    return False
